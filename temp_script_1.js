        function renderTimeline() {
            const timelineContainer = document.getElementById('chronologicalTimeline');
            if (!timelineContainer) return;

            let allDeadlines = [];

            vehicles.forEach(v => {
                for (let key in v.deadlines) {
                    if (key !== 'altroNota' && v.deadlines[key]) {
                        allDeadlines.push({
                            label: `${v.plate} - ${getDeadlineFriendlyName(key)}`,
                            date: v.deadlines[key],
                            state: checkDeadlineState(v.deadlines[key]),
                            resourceType: 'vehicle',
                            id: v.id
                        });
                    }
                }
            });

            operators.forEach(op => {
                if (op.type === 'driver') {
                    if (op.expiration) {
                        allDeadlines.push({
                            label: `${op.name} (Scadenza Card)`,
                            date: op.expiration,
                            state: checkDeadlineState(op.expiration),
                            resourceType: 'operator',
                            id: op.id
                        });
                    }
                    if (op.lastDownload) {
                        const nextDate = calculateNextDownloadDate(op.lastDownload);
                        allDeadlines.push({
                            label: `${op.name} (Scarico Conducente)`,
                            date: nextDate,
                            state: checkDeadlineState(nextDate),
                            resourceType: 'operator',
                            id: op.id
                        });
                    }
                } else if (op.expiration) {
                    allDeadlines.push({
                        label: `${op.name} (${op.type === 'company' ? 'Aziendale' : 'Mezzo'})`,
                        date: op.expiration,
                        state: checkDeadlineState(op.expiration),
                        resourceType: 'operator',
                        id: op.id
                    });
                }
            });

            allDeadlines.sort((a, b) => new Date(a.date) - new Date(b.date));
            const top5 = allDeadlines.slice(0, 5);

            if (top5.length === 0) {
                timelineContainer.innerHTML = `<p class="col-span-5 text-center text-xs text-slate-400 py-4">Nessuna scadenza inserita.</p>`;
                return;
            }

            timelineContainer.innerHTML = top5.map(d => {
                let badgeClass = "bg-slate-100 text-slate-800 dark:bg-slate-700 dark:text-slate-300";
                if (d.state === 'red') badgeClass = "bg-red-500 text-white";
                else if (d.state === 'amber') badgeClass = "bg-amber-500 text-white";
                else if (d.state === 'emerald') badgeClass = "bg-emerald-600 text-white";

                return `
                    <div class="p-2.5 bg-slate-50 dark:bg-slate-900/60 rounded-xl border border-slate-200 dark:border-slate-700 flex flex-col justify-between">
                        <div class="flex items-center justify-between gap-1 mb-1">
                            <span class="text-[9px] px-1.5 py-0.5 rounded-full font-bold uppercase truncate tracking-wider ${badgeClass}">
                                ${formatDateString(d.date)}
                            </span>
                            <i data-lucide="${d.resourceType === 'vehicle' ? 'truck' : 'user'}" class="w-3.5 h-3.5 text-slate-400"></i>
                        </div>
                        <p class="text-[11px] font-bold text-slate-700 dark:text-slate-300 truncate" title="${d.label}">${d.label}</p>
                    </div>
                `;
            }).join('');

            lucide.createIcons();
        }

