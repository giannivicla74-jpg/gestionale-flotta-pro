        function buildNotificationPanelList(expired, expiring) {
            const listContainer = document.getElementById('notificationList');
            if (!listContainer) return;

            let issues = [];
            vehicles.forEach(v => {
                for (let k in v.deadlines) {
                    if (k !== 'altroNota' && v.deadlines[k]) {
                        const state = checkDeadlineState(v.deadlines[k]);
                        if (state === 'red' || state === 'amber') {
                            issues.push({
                                label: `${v.plate} - ${getDeadlineFriendlyName(k)}`,
                                state: state,
                                date: v.deadlines[k]
                            });
                        }
                    }
                }
            });

            operators.forEach(op => {
                if (op.type === 'driver') {
                    const stateExp = checkDeadlineState(op.expiration);
                    if (stateExp === 'red' || stateExp === 'amber') {
                        issues.push({
                            label: `${op.name} (Fisica Card)`,
                            state: stateExp,
                            date: op.expiration
                        });
                    }
                    const stateDl = checkDownloadDeadlineState(op.lastDownload);
                    if (stateDl === 'red' || stateDl === 'amber') {
                        issues.push({
                            label: `${op.name} (Scarico 28gg)`,
                            state: stateDl,
                            date: calculateNextDownloadDate(op.lastDownload)
                        });
                    }
                } else {
                    const stateExp = checkDeadlineState(op.expiration);
                    if (stateExp === 'red' || stateExp === 'amber') {
                        issues.push({
                            label: `${op.name} (Fisica Card ${op.type === 'company' ? 'Aziendale' : 'Scarico Mezzo'})`,
                            state: stateExp,
                            date: op.expiration
                        });
                    }
                    const stateDl = checkCompanyDownloadDeadlineState(op.lastDownload);
                    if (stateDl === 'red' || stateDl === 'amber') {
                        issues.push({
                            label: `${op.name} (Scarico 90gg ${op.type === 'company' ? 'Aziendale' : 'Scarico Mezzo'})`,
                            state: stateDl,
                            date: calculateNextCompanyDownloadDate(op.lastDownload)
                        });
                    }
                }
            });

            if (issues.length === 0) {
                listContainer.innerHTML = `<p class="text-center py-4 text-slate-400">Tutti i mezzi e le tessere aziendali sono in regola. Ottimo lavoro!</p>`;
                return;
            }

            issues.sort((a,b) => new Date(a.date) - new Date(b.date));

            listContainer.innerHTML = issues.map(issue => {
                const isExpired = issue.state === 'red';
                const color = isExpired ? 'text-red-500 animate-pulse' : 'text-amber-500';
                return `
                    <div class="flex items-center justify-between p-2 rounded-lg bg-slate-50 dark:bg-slate-900 border-l-4 ${isExpired ? 'border-red-500' : 'border-amber-500'}">
                        <div class="max-w-[190px]">
                            <p class="font-bold text-slate-700 dark:text-slate-300 truncate">${issue.label}</p>
                            <p class="text-[10px] text-slate-400 font-mono">${formatDateString(issue.date)}</p>
                        </div>
                        <span class="text-[9px] uppercase font-extrabold ${color}">
                            ${isExpired ? 'Scaduto' : 'In Scadenza'}
                        </span>
                    </div>
                `;
            }).join('');
        }

