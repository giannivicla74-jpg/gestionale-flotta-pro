        function renderDeadlineBox(title, dateString) {
            const state = checkDeadlineState(dateString);
            let bgClass = "bg-slate-100 dark:bg-slate-850 border-slate-200 dark:border-slate-700 text-slate-400 dark:text-slate-500";
            let badgeClass = "bg-slate-200 dark:bg-slate-700 text-slate-600 dark:text-slate-300";
            let statusText = "Non impostato";
            let iconMarkup = '<i data-lucide="minus" class="w-3 h-3"></i>';
            let daysRemainingText = "";

            if (dateString) {
                const today = new Date();
                today.setHours(0,0,0,0);
                const deadlineDate = new Date(dateString);
                deadlineDate.setHours(0,0,0,0);
                const diffTime = deadlineDate - today;
                const diffDays = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

                if (state === 'red') {
                    bgClass = "bg-red-50 dark:bg-red-950/20 border-red-200 dark:border-red-900/60 text-red-900 dark:text-red-300";
                    badgeClass = "bg-red-600 text-white font-bold animate-pulse";
                    const overdue = Math.abs(diffDays);
                    statusText = "SCADUTO";
                    iconMarkup = '<i data-lucide="alert-triangle" class="w-3 h-3"></i>';
                    daysRemainingText = `<span class="text-[11px] text-red-600 dark:text-red-400 font-bold block mt-1">Scaduto da ${overdue} ${overdue === 1 ? 'giorno' : 'giorni'} ⚠️</span>`;
                } else if (state === 'amber') {
                    bgClass = "bg-amber-50 dark:bg-amber-950/20 border-amber-200 dark:border-amber-900/60 text-amber-900 dark:text-amber-300";
                    badgeClass = "bg-amber-500 text-white font-bold";
                    statusText = "IN SCADENZA";
                    iconMarkup = '<i data-lucide="clock" class="w-3 h-3"></i>';
                    daysRemainingText = `<span class="text-[11px] text-amber-600 dark:text-amber-400 font-bold block mt-1">Mancano ${diffDays} ${diffDays === 1 ? 'giorno' : 'giorni'} ⏳</span>`;
                } else if (state === 'emerald') {
                    bgClass = "bg-emerald-50/50 dark:bg-emerald-950/10 border-emerald-200 dark:border-emerald-900/60 text-emerald-950 dark:text-emerald-300";
                    badgeClass = "bg-emerald-600 text-white font-bold";
                    statusText = "OK";
                    iconMarkup = '<i data-lucide="check" class="w-3 h-3"></i>';
                    daysRemainingText = `<span class="text-[11px] text-emerald-600 dark:text-emerald-400 font-semibold block mt-1">Mancano ${diffDays} giorni ✅</span>`;
                }
            }

            const formattedDate = dateString ? formatDateString(dateString) : '--/--/----';

            return `
                <div class="border rounded-xl p-3 flex flex-col justify-between ${bgClass} transition-all">
                    <div class="flex justify-between items-start gap-1">
                        <span class="text-[10px] font-bold uppercase tracking-wide opacity-80 truncate" title="${title}">${title}</span>
                        <span class="text-[8px] px-1.5 py-0.5 rounded-full uppercase tracking-wider ${badgeClass} flex items-center gap-0.5 font-bold">
                            ${iconMarkup} <span>${statusText}</span>
                        </span>
                    </div>
                    <div class="mt-1 flex flex-col justify-end">
                        <div class="text-sm font-extrabold tracking-wider font-mono dark:text-white">
                            ${formattedDate}
                        </div>
                        ${daysRemainingText}
                    </div>
                </div>
            `;
        }

