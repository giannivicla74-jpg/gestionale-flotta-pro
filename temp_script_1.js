        function importJSON(event) {
            const file = event.target.files[0];
            if (!file) return;

            const reader = new FileReader();
            reader.onload = function(e) {
                try {
                    const parsed = JSON.parse(e.target.result);
                    if (parsed.vehicles && parsed.operators) {
                        
                        const repairedOperators = parsed.operators.map(op => {
                            if (op.type === 'driver' && !op.lastDownload) {
                                return {
                                    ...op,
                                    lastDownload: new Date().toISOString().split('T')[0]
                                };
                            }
                            return op;
                        });

                        vehicles = parsed.vehicles;
                        operators = repairedOperators;
                        
                        saveToStorage(); 
                        loadFromStorage();
                        showToast("Dati e vecchi backup ripristinati con successo nel database!", "success");
                    } else {
                        showToast("Formato file non supportato o non compatibile.", "error");
                    }
                } catch (err) {
                    showToast("Errore di caricamento o file corrotto.", "error");
                }
            };
            reader.readAsText(file);
        }

